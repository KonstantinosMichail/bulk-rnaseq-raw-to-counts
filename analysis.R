# ============================================================
# Bulk RNA-seq Differential Expression Analysis
# Saccharomyces cerevisiae
#
# This script starts from featureCounts gene-level counts
# and performs differential expression analysis using DESeq2.
#
# Biological comparison:
# High protein production vs Low protein production
#
# IMPORTANT:
# In this dataset, protein production is completely confounded
# with strain:
#   AAC  = low protein production
#   B184 = high protein production
#
# Therefore, the results represent differences between the
# B184/high-production and AAC/low-production groups. The effect
# of protein production cannot be separated from the effect of
# strain in this experimental design.
# ============================================================


# ------------------------------------------------------------
# 1. Load required R packages
# ------------------------------------------------------------

library(DESeq2)
library(ggplot2)


# ------------------------------------------------------------
# 2. Load featureCounts output and sample metadata
# ------------------------------------------------------------

# Read the gene-level count table generated by featureCounts.
counts <- read.delim(
  "counts/gene_counts.txt",
  comment.char = "#",
  check.names = FALSE
)

# Load sample metadata describing each sequencing sample.
metadata <- read.delim("metadata.tsv")


# ------------------------------------------------------------
# 3. Extract the gene count matrix
# ------------------------------------------------------------

# The first six columns of the featureCounts output contain
# annotation information:
#   Geneid, Chr, Start, End, Strand, Length
#
# The remaining columns contain the read counts for each sample.
count_matrix <- counts[, 7:ncol(counts)]

# Use gene IDs as row names.
rownames(count_matrix) <- counts$Geneid


# ------------------------------------------------------------
# 4. Clean sample names
# ------------------------------------------------------------

# featureCounts uses the BAM file paths as sample column names.
# Remove the "alignment/" directory prefix.
colnames(count_matrix) <- sub(
  "^alignment/",
  "",
  colnames(count_matrix)
)

# Remove the STAR BAM filename suffix.
# This leaves the original SRA accession as the sample ID.
colnames(count_matrix) <- sub(
  "\\.Aligned\\.sortedByCoord\\.out\\.bam$",
  "",
  colnames(count_matrix)
)


# ------------------------------------------------------------
# 5. Match count matrix samples with metadata
# ------------------------------------------------------------

# Check that the sample names in the count matrix correspond
# exactly to the sample names in the metadata.
stopifnot(all(colnames(count_matrix) == metadata$sample))

# Use sample IDs as metadata row names.
rownames(metadata) <- metadata$sample

# Convert protein production into a categorical variable.
# "low" is specified as the reference level, so the DESeq2
# comparison will be high vs low.
metadata$protein_production <- factor(
  metadata$protein_production,
  levels = c("low", "high")
)

# Reorder metadata to exactly match the count matrix columns.
metadata <- metadata[colnames(count_matrix), ]

# Final check that metadata and count matrix are perfectly aligned.
stopifnot(identical(rownames(metadata), colnames(count_matrix)))


# ------------------------------------------------------------
# 6. Filter low-count genes
# ------------------------------------------------------------

# Retain genes with at least 10 reads in at least 3 samples.
#
# This removes genes with extremely low counts that provide
# little reliable information for differential expression.
keep <- rowSums(count_matrix >= 10) >= 3

count_matrix_filtered <- count_matrix[keep, ]


# ------------------------------------------------------------
# 7. Create the DESeq2 dataset
# ------------------------------------------------------------

# Create a DESeqDataSet using:
#   - the filtered raw count matrix
#   - the sample metadata
#   - protein production as the experimental variable
dds <- DESeqDataSetFromMatrix(
  countData = count_matrix_filtered,
  colData = metadata,
  design = ~ protein_production
)


# ------------------------------------------------------------
# 8. Run the DESeq2 analysis
# ------------------------------------------------------------

dds <- DESeq(dds)


# ------------------------------------------------------------
# 9. Extract differential expression results
# ------------------------------------------------------------

# Positive log2 fold changes:
#   Higher expression in the high-production group.
#
# Negative log2 fold changes:
#   Higher expression in the low-production group.
res <- results(
  dds,
  contrast = c("protein_production", "high", "low")
)


# ------------------------------------------------------------
# 10. Convert results to a regular data frame
# ------------------------------------------------------------

res_df <- as.data.frame(res)

# Preserve the gene IDs as an explicit column.
res_df$gene_id <- rownames(res_df)

# Arrange the columns in a logical order.
res_df <- res_df[, c(
  "gene_id",
  "baseMean",
  "log2FoldChange",
  "lfcSE",
  "stat",
  "pvalue",
  "padj"
)]


# ------------------------------------------------------------
# 11. MA plot
# ------------------------------------------------------------

# Visualize the relationship between average expression and
# log2 fold change.
#
# X-axis:
#   Mean normalized expression.
#
# Y-axis:
#   Log2 fold change (high vs low production).
plotMA(
  res,
  ylim = c(-5, 5)
)


# ------------------------------------------------------------
# 12. Define significant differentially expressed genes
# ------------------------------------------------------------

# Start by classifying all genes as not significant.
res_df$significance <- "Not significant"

# Genes significantly upregulated in the high-production group:
#   adjusted p-value < 0.05
#   log2 fold change > 1
#
# log2FC > 1 corresponds to more than a 2-fold increase.
res_df$significance[
  res_df$padj < 0.05 &
    res_df$log2FoldChange > 1
] <- "Up"

# Genes significantly downregulated in the high-production group:
#   adjusted p-value < 0.05
#   log2 fold change < -1
#
# log2FC < -1 corresponds to more than a 2-fold decrease.
res_df$significance[
  res_df$padj < 0.05 &
    res_df$log2FoldChange < -1
] <- "Down"


# ------------------------------------------------------------
# 13. Volcano plot
# ------------------------------------------------------------

# Plot statistical significance against effect size.
#
# X-axis:
#   Log2 fold change.
#
# Y-axis:
#   -log10(adjusted p-value).
#
# Dashed vertical lines:
#   log2FC = -1 and +1.
#
# Dashed horizontal line:
#   adjusted p-value = 0.05.
ggplot(
  res_df,
  aes(
    x = log2FoldChange,
    y = -log10(padj),
    color = significance
  )
) +
  geom_point(alpha = 0.6) +
  geom_vline(
    xintercept = c(-1, 1),
    linetype = "dashed"
  ) +
  geom_hline(
    yintercept = -log10(0.05),
    linetype = "dashed"
  ) +
  labs(
    title = "Differential Expression: High vs Low Protein Production",
    x = "log2 Fold Change",
    y = "-log10 Adjusted p-value"
  ) +
  theme_minimal()


# ------------------------------------------------------------
# 14. Save complete differential expression results
# ------------------------------------------------------------

# Save results for all genes tested by DESeq2.
write.csv(
  res_df,
  "results/differential_expression_results.csv",
  row.names = FALSE
)


# ------------------------------------------------------------
# 15. Save significant differentially expressed genes
# ------------------------------------------------------------

# Select genes satisfying both significance criteria:
#   adjusted p-value < 0.05
#   absolute log2 fold change > 1
sig_res <- subset(
  res_df,
  padj < 0.05 &
    abs(log2FoldChange) > 1
)

# Save the significant DEG table.
write.csv(
  sig_res,
  "results/significant_DEGs.csv",
  row.names = FALSE
)
